Ptr32<void> w3d_heap_morecore(int requested)
{
    unsigned int old_break;
    char buffer[256];
    if (w3d_heap_break == 0) {
        w3d_heap_break = ((unsigned int)w3d::H(w3d_heap_arena_low()) + 31) & ~31UL;
        w3d_heap_start = ((unsigned int)w3d::H(w3d_heap_arena_low()) + 31) & ~31UL;
        w3d_heap_limit = (unsigned int)w3d::H(w3d_heap_arena_high()) & ~31UL;
    }
    old_break = w3d_heap_break;
    if ((unsigned int)requested > w3d_heap_limit - w3d_heap_break) {
        w3d_heap_format(buffer, w3d_heap_format_error, requested / 1024);
        w3d_heap_error(buffer, 0);
    }
    w3d_heap_break += requested;
    w3d_heap_trace(w3d_heap_format_trace,
                   (w3d_heap_break - w3d_heap_start) / 1024,
                   (w3d_heap_limit - w3d_heap_break) / 1024,
                   requested / 1024);
    return (Ptr32<void>)w3d::G(old_break);
}

